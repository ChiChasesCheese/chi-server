#!/usr/bin/env bash
# System settings for running macOS as a server. Needs sudo. Idempotent.
# Every setting says why; if you disagree with one, comment out that line.
set -euo pipefail
. "$(dirname "$0")/lib.sh"
require_macos
[ -f "$CHI_ROOT/.env" ] && load_env

log "macOS server settings (asks for your sudo password)"
sudo -v

# ---------- Power ----------
# sleep 0         never sleep (a sleeping server is a down server)
# disksleep 0     don't spin down disks (external drives too, or every access stalls for seconds)
# displaysleep 10 the display may sleep; it doesn't affect services
# powernap 0      a server doesn't need Power Nap; it causes odd half-asleep states
# womp 1          allow Wake on LAN
# autorestart 1   power back on after a power failure <- the most important one
# tcpkeepalive 1  keep TCP connections alive
sudo pmset -a sleep 0 disksleep 0 displaysleep 10 powernap 0 womp 1 autorestart 1 tcpkeepalive 1
ok "pmset: never sleep / restart after power loss / wake on LAN"

# Restart automatically after a system freeze. On recent macOS some systemsetup subcommands need Full Disk Access; skip on failure
sudo systemsetup -setrestartfreeze on >/dev/null 2>&1 && ok "Restart after freeze enabled" \
  || warn "systemsetup needs Full Disk Access for your terminal; skipping restartfreeze (not essential)"

# ---------- Hostname ----------
if [ -n "${CHI_HOSTNAME:-}" ]; then
  if [ "$(scutil --get LocalHostName 2>/dev/null || true)" != "$CHI_HOSTNAME" ]; then
    sudo scutil --set ComputerName "$CHI_HOSTNAME"
    sudo scutil --set HostName "$CHI_HOSTNAME"
    sudo scutil --set LocalHostName "$CHI_HOSTNAME"
    ok "Hostname -> ${CHI_HOSTNAME} (reachable on the LAN as ${CHI_HOSTNAME}.local)"
  fi
fi

# ---------- Firewall ----------
# Application firewall on + stealth mode (no ping replies, no answers to port probes).
# allowsigned / allowsignedapp: automatically allow Apple and developer-signed apps (OrbStack and Tailscale are),
# otherwise ports forwarded by OrbStack get blocked and the LAN can't reach them.
FW=/usr/libexec/ApplicationFirewall/socketfilterfw
sudo "$FW" --setglobalstate on >/dev/null
sudo "$FW" --setstealthmode on >/dev/null
sudo "$FW" --setallowsigned on >/dev/null
sudo "$FW" --setallowsignedapp on >/dev/null
ok "Firewall: on + stealth mode + signed apps allowed"

# ---------- SSH (Remote Login) ----------
if ! nc -z 127.0.0.1 22 >/dev/null 2>&1; then
  if sudo systemsetup -setremotelogin on >/dev/null 2>&1; then
    ok "Remote Login (SSH) enabled"
  else
    warn "Can't enable SSH from the command line (needs Full Disk Access). Do it by hand: System Settings -> General -> Sharing -> Remote Login"
  fi
else
  ok "SSH is already listening"
fi

# Key-only login - only if you've already installed a public key, otherwise you'd lock yourself out, hence the guard.
# Off by default (enable with CHI_SSH_KEY_ONLY=1); see "Mode B: FileVault on" in docs/operations.md:
# FileVault pre-boot SSH unlock on macOS 26 uses a password, and it's unconfirmed whether disabling password login
# affects it - verify it yourself once.
DROPIN=/etc/ssh/sshd_config.d/000-chi.conf
if [ "${CHI_SSH_KEY_ONLY:-0}" = "1" ]; then
  if [ -s "$HOME/.ssh/authorized_keys" ]; then
    sudo tee "$DROPIN" >/dev/null <<'EOF'
# Generated by chi-server scripts/macos.sh. sshd uses the first value it sees, so the 000 prefix sorts this file first.
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
EOF
    sudo sshd -t && ok "SSH is now key-only (${DROPIN})"
  else
    warn "$HOME/.ssh/authorized_keys is empty; not enabling key-only login (you'd lock yourself out). Run ssh-copy-id from your computer first"
  fi
fi

# ---------- System updates ----------
# Check, download, and install security fixes automatically (Rapid Security Responses / XProtect),
# but *not* macOS major/minor updates - those reboot, and with FileVault on the Mac stops at the unlock screen.
SU=/Library/Preferences/com.apple.SoftwareUpdate
sudo defaults write "$SU" AutomaticCheckEnabled -bool true
sudo defaults write "$SU" AutomaticDownload -bool true
sudo defaults write "$SU" CriticalUpdateInstall -bool true
sudo defaults write "$SU" ConfigDataInstall -bool true
# The key line: don't auto-install macOS updates (System Settings -> General -> Software Update -> Automatic Updates ->
# "Install macOS updates"). The two above (CriticalUpdateInstall = security responses, ConfigDataInstall = XProtect
# and other security data) stay automatic.
sudo defaults write "$SU" AutomaticallyInstallMacOSUpdates -bool false
sudo defaults write /Library/Preferences/com.apple.commerce AutoUpdateRestartRequired -bool false
ok "Updates: auto-download + auto-install security fixes; do OS upgrades by hand (the docs cover rebooting with FileVault)"

# ---------- Status report (read-only, hints only) ----------
fv="$(fdesetup status 2>/dev/null || true)"
log "FileVault: $fv"
case "$fv" in
  *"On"*) warn "FileVault is on: after a reboot the disk must be unlocked before services run. Read docs/operations.md (unattended mode) and pick a mode" ;;
esac

ok "macOS settings done. A few items must be clicked in System Settings; see the checklist in docs/getting-started.md"
