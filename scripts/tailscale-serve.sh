#!/usr/bin/env bash
# Expose local services over HTTPS to your tailnet with `tailscale serve` (reachable only from your devices).
#
# Why this instead of Caddy/Nginx + your own domain:
#   - Tailscale issues and renews the certificates (Let's Encrypt) with zero config
#   - no domain, no open ports, no DNS
#   - cost: URLs look like https://<machine>.<tailnet>.ts.net:<port>; see docs/remote-access.md for prettier names
#
# Note: once HTTPS certificates are on, the machine name appears in public Certificate Transparency logs.
# Only the name - not the services.
#
# Port mappings come from each enabled stack's stack.conf (SERVE="<https_port>=<local_port> ...").
set -euo pipefail
. "$(dirname "$0")/lib.sh"
require_macos
ensure_brew_path
load_env

url_for() {  # https_port -> printable URL
  if [ "$1" = 443 ]; then echo "https://$TS_FQDN"; else echo "https://$TS_FQDN:$1"; fi
}

action="${1:-apply}"
case "$action" in
  apply)
    [ -n "${TS_FQDN:-}" ] || die "TS_FQDN is empty in .env. Run 'chi bootstrap tailscale', then 'chi init'"
    for s in $(resolve_stacks); do
      for pair in $(stack_conf "$s" SERVE); do
        https="${pair%%=*}"; local_port="${pair##*=}"
        sudo_ts serve --bg --https="$https" "http://127.0.0.1:$local_port" >/dev/null
        ok "$s  $(url_for "$https")  ->  127.0.0.1:$local_port"
      done
    done
    # Onboarding page + PAC file (static files generated by `chi onboard`)
    if [ -f "$DATA_DIR/share/index.html" ]; then
      sudo_ts serve --bg --https=8008 "$DATA_DIR/share" >/dev/null
      ok "share  $(url_for 8008)  ->  $DATA_DIR/share (onboarding page)"
    fi
    # Split-routing proxy dashboard - only while the proxy service is actually running
    if brew services list 2>/dev/null | grep -q '^mihomo.*started'; then
      sudo_ts serve --bg --https=8007 "http://127.0.0.1:9090" >/dev/null
      ok "proxy  $(url_for 8007)/ui  ->  127.0.0.1:9090 (dashboard backend: $(url_for 8007), secret: CLASH_SECRET in .env)"
    else
      sudo_ts serve --https=8007 off >/dev/null 2>&1 || true
    fi
    ;;
  status) tailscale serve status ;;
  reset)  sudo_ts serve reset && ok "All serve rules cleared" ;;
  *) die "Usage: chi serve [apply|status|reset]" ;;
esac
