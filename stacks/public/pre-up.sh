#!/usr/bin/env bash
# Before chi up public: enable cloudflared (compose profile "tunnel") only when CF_TUNNEL_TOKEN is set
set -euo pipefail
. "$(dirname "$0")/../../scripts/lib.sh"
load_env

env_file="$(dirname "$0")/.env"
if [ -n "${CF_TUNNEL_TOKEN:-}" ]; then
  profiles=tunnel
  ok "Cloudflare Tunnel configured: starting cloudflared (tunnel status: Cloudflare dashboard -> Networking -> Tunnels)"
else
  profiles=
  warn "CF_TUNNEL_TOKEN is empty in .env: starting only the sample app, not connecting to Cloudflare (setup: docs/modules/public.md)"
  # A token was set before and is now cleared: compose ignores services of an inactive profile, so remove the container
  # explicitly to make sure it really goes offline
  if docker ps -a --format '{{.Names}}' 2>/dev/null | grep -qx chi-cloudflared; then
    docker rm -f chi-cloudflared >/dev/null
    ok "Removed the old chi-cloudflared container (public entry is closed)"
  fi
fi
{
  echo "# Generated by stacks/public/pre-up.sh - do not edit"
  echo "COMPOSE_PROFILES=${profiles}"
} >"$env_file"
