#!/usr/bin/env bash
# Before chi up scrape: start the LiteLLM gateway only when AI features are on (FIRECRAWL_MODEL set), and check
# that the backend it routes to is usable
set -euo pipefail
. "$(dirname "$0")/../../scripts/lib.sh"
load_env

env_file="$(dirname "$0")/.env"
model="${FIRECRAWL_MODEL:-}"
if [ -z "$model" ]; then
  echo "# Generated by stacks/scrape/pre-up.sh - do not edit" >"$env_file"
  ok "Firecrawl AI features off (FIRECRAWL_MODEL is empty); scraping and crawling work without them"
  exit 0
fi
[ -n "${FIRECRAWL_LLM_KEY:-}" ] || die "FIRECRAWL_LLM_KEY is empty: run chi init to generate it"
{
  echo "# Generated by stacks/scrape/pre-up.sh - do not edit"
  echo "COMPOSE_PROFILES=ai"
} >"$env_file"

case "$model" in
  claude-*)
    [ -n "${ANTHROPIC_API_KEY:-}" ] || warn "FIRECRAWL_MODEL=$model needs ANTHROPIC_API_KEY in .env; AI features will fail" ;;
  *)
    ollama list 2>/dev/null | awk 'NR>1 {print $1}' | grep -qx "$model" ||
      warn "Ollama has no model $model (ollama pull $model); AI features will fail" ;;
esac
# Embeddings for link ranking always come from Ollama
ollama list 2>/dev/null | awk 'NR>1 {print $1}' | grep -q '^nomic-embed-text' ||
  warn "Ollama has no nomic-embed-text (ollama pull nomic-embed-text); /extract on whole sites will fail"
ok "Firecrawl AI features on: $model through the LiteLLM gateway"
