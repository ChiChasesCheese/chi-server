#!/usr/bin/env bash
# Before chi up media: create directories; generate MeTube's yt-dlp options (using the China proxy if it's running)
set -euo pipefail
. "$(dirname "$0")/../../scripts/lib.sh"
load_env
MEDIA_DIR="${MEDIA_DIR:-$DATA_DIR/media}"
mkdir -p "$MEDIA_DIR/Downloads" "$MEDIA_DIR/Keep" "$MEDIA_DIR/Movies" "$MEDIA_DIR/TV" \
  "$DATA_DIR/jellyfin/config" "$DATA_DIR/jellyfin/cache" "$DATA_DIR/metube"

env_file="$(dirname "$0")/.env"
port="${CLASH_PORT:-7890}"
# Prefer H.264 + AAC: YouTube defaults to AV1/VP9, which older TV boxes can't hardware-decode, and Jellyfin in a
# container has no hardware transcoding, so the CPU would have to carry it
sort='"format_sort": ["vcodec:h264", "acodec:aac"]'
if nc -z 127.0.0.1 "$port" >/dev/null 2>&1; then
  # All downloads go through mihomo: Bilibili etc. route via China, YouTube etc. go direct per the rules
  opts="{$sort, \"proxy\": \"http://host.docker.internal:$port\"}"
  ok "MeTube will download through mihomo (mainland-only Bilibili content available)"
else
  opts="{$sort}"
  warn "mihomo is not running: MeTube downloads directly (mainland-only Bilibili content will fail; run chi proxy install if needed)"
fi
{
  echo "# Generated by stacks/media/pre-up.sh - do not edit"
  echo "MEDIA_DIR=$MEDIA_DIR"
  echo "METUBE_YTDL_OPTIONS='$opts'"
} >"$env_file"
